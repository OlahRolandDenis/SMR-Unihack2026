-- Smart Cultural Lanterns — Tiger Data (PostgreSQL + TimescaleDB) schema
-- Run once with: psql $DATABASE_URL -f db/schema.sql
-- (or via the init_db() helper in app/db.py)

-- ============================================================
-- USERS — mirrors Auth0; the Auth0 "sub" claim is the primary key
-- ============================================================
CREATE TABLE IF NOT EXISTS users (
    id          TEXT PRIMARY KEY,          -- Auth0 sub, e.g. 'google-oauth2|1234'
    email       TEXT NOT NULL,
    name        TEXT,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- ============================================================
-- LANTERNS — one row per physical lantern; id is the QR slug (/f/unirii)
-- ============================================================
CREATE TABLE IF NOT EXISTS lanterns (
    id          TEXT PRIMARY KEY,          -- QR slug: 'unirii', 'victoriei', ...
    name        TEXT NOT NULL,             -- display name: 'Piața Unirii'
    description TEXT,
    latitude    DOUBLE PRECISION,
    longitude   DOUBLE PRECISION,
    state       TEXT NOT NULL DEFAULT 'idle',  -- 'idle' | 'playing' | 'crowded' — sent to ESP32, drives WiZ color
    last_seen   TIMESTAMPTZ,                   -- stamped on every ESP32 poll; NULL/stale = offline
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- ============================================================
-- STORIES — one row per recorded memory; RO + EN kept as flat columns
-- status flow: processing -> approved | rejected | pending_review
-- ============================================================
CREATE TABLE IF NOT EXISTS stories (
    id              UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    lantern_id      TEXT NOT NULL REFERENCES lanterns(id) ON DELETE CASCADE,
    user_id         TEXT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    status          TEXT NOT NULL DEFAULT 'processing',
                    -- 'processing' | 'approved' | 'rejected' | 'pending_review'
    reject_reason   TEXT,                  -- filled by Gemini or a moderator on rejection
    consent         BOOLEAN NOT NULL DEFAULT FALSE,  -- public broadcast consent checkbox
    language_original TEXT,                -- BCP-47 detected by Gemini, e.g. 'ro'
    transcript_original TEXT,              -- raw transcription
    text_ro         TEXT,                  -- Gemini translation (Romanian)
    text_en         TEXT,                  -- Gemini translation (English)
    audio_ro_url    TEXT,                  -- '/audio/<story_id>_ro.mp3' (relative; served statically)
    audio_en_url    TEXT,
    solana_tx       TEXT,                  -- optional: on-chain hash tx signature
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    reviewed_at     TIMESTAMPTZ            -- set when a moderator decides
);

CREATE INDEX IF NOT EXISTS idx_stories_user    ON stories (user_id, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_stories_lantern ON stories (lantern_id, status, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_stories_review  ON stories (status) WHERE status = 'pending_review';

-- ============================================================
-- PLAY QUEUE — "trigger the lantern" requests; ESP32 poll pops the oldest
-- ============================================================
CREATE TABLE IF NOT EXISTS play_queue (
    id           BIGSERIAL PRIMARY KEY,
    lantern_id   TEXT NOT NULL REFERENCES lanterns(id) ON DELETE CASCADE,
    story_id     UUID NOT NULL REFERENCES stories(id) ON DELETE CASCADE,
    lang         TEXT NOT NULL DEFAULT 'ro',   -- 'ro' | 'en'
    -- queued -> delivering (handed to ESP32 on poll) -> delivered (ESP32 acked
    -- playback). Un-acked items are requeued after 75 s, 3 tries, then 'failed'.
    status       TEXT NOT NULL DEFAULT 'queued',  -- 'queued' | 'delivering' | 'delivered' | 'failed'
    requested_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    delivered_at TIMESTAMPTZ,                     -- when last handed out
    delivery_attempts INT NOT NULL DEFAULT 0      -- requeue count after lost handoffs
);

CREATE INDEX IF NOT EXISTS idx_queue_pending
    ON play_queue (lantern_id, requested_at) WHERE status = 'queued';

-- ============================================================
-- PRESENCE PINGS — time-series hypertable (the Tiger Data milestone)
-- Frontend pings every 15s; a user counts as present if pinged < 45s ago.
-- ============================================================
CREATE TABLE IF NOT EXISTS presence_pings (
    time        TIMESTAMPTZ NOT NULL DEFAULT now(),
    lantern_id  TEXT NOT NULL,             -- no FK: keeps hypertable inserts cheap
    session_id  UUID NOT NULL,             -- anonymous session id generated by the frontend
    user_id     TEXT                       -- Auth0 sub when logged in, else NULL
);

-- Convert to a hypertable (idempotent). Tiger Data ships TimescaleDB preinstalled.
SELECT create_hypertable('presence_pings', 'time', if_not_exists => TRUE);

CREATE INDEX IF NOT EXISTS idx_pings_lantern_time
    ON presence_pings (lantern_id, time DESC);

